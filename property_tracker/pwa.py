"""Serve the web-app manifest and service worker that make /property-tracker installable.

Frappe's www folder won't serve .js/.json files, so these are produced by a
custom page renderer (hooks.page_renderer). The service worker lives at the
site root so its scope can cover /property-tracker.
"""

import json

import frappe
from frappe.utils import get_build_version
from werkzeug.wrappers import Response

MANIFEST_PATH = "property-tracker.webmanifest"
SW_PATH = "property-tracker-sw.js"
IMG = "/assets/property_tracker/images"


def manifest():
	return {
		"id": "/property-tracker",
		"name": "Property Tracker",
		"short_name": "Properties",
		"description": "Track property and land site visits",
		"start_url": "/property-tracker",
		"scope": "/property-tracker",
		"display": "standalone",
		"orientation": "portrait",
		"background_color": "#f6f5f2",
		"theme_color": "#1f6f50",
		"icons": [
			{"src": f"{IMG}/icon-192.png", "sizes": "192x192", "type": "image/png", "purpose": "any"},
			{"src": f"{IMG}/icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "any"},
			{"src": f"{IMG}/icon-maskable-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"},
		],
	}


SERVICE_WORKER = """// Property Tracker service worker (generated by property_tracker/pwa.py)
const CACHE = "property-tracker-__VERSION__";
const PAGE = "/property-tracker";
const SHELL = [
  "/assets/property_tracker/css/property_tracker.css?v=__VERSION__",
  "/assets/property_tracker/js/property_tracker.js?v=__VERSION__",
  "/assets/property_tracker/images/logo.svg",
  "https://unpkg.com/leaflet@1.9.4/dist/leaflet.css",
  "https://unpkg.com/leaflet@1.9.4/dist/leaflet.js",
];
const OFFLINE = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Offline</title>
<style>body{font:16px system-ui,sans-serif;display:grid;place-items:center;min-height:100vh;margin:0;background:#f6f5f2;color:#1d2320;text-align:center;padding:24px}button{background:#1f6f50;color:#fff;border:0;border-radius:10px;padding:12px 20px;font:inherit}</style></head>
<body><div><h2>You're offline</h2><p>Property Tracker needs a connection to load your data.</p><button onclick="location.reload()">Try again</button></div></body></html>`;

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => Promise.allSettled(SHELL.map((u) => c.add(u)))).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("property-tracker-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);

  // The page itself: always try the network (fresh data, CSRF token, login redirects).
  if (req.mode === "navigate" && url.pathname === PAGE) {
    e.respondWith(
      fetch(req)
        .then((res) => {
          if (res.ok && !res.redirected) caches.open(CACHE).then((c) => c.put(PAGE, res.clone()));
          return res;
        })
        .catch(() => caches.match(PAGE).then((r) => r || new Response(OFFLINE, { headers: { "Content-Type": "text/html" } })))
    );
    return;
  }

  // Static app assets and Leaflet: serve from cache, refresh in the background.
  const isShell = url.pathname.startsWith("/assets/property_tracker/") || url.href.startsWith("https://unpkg.com/leaflet@1.9.4/");
  if (isShell) {
    e.respondWith(
      caches.open(CACHE).then((c) =>
        c.match(req).then((hit) => {
          const net = fetch(req).then((res) => { if (res.ok || res.type === "opaque") c.put(req, res.clone()); return res; });
          return hit || net;
        })
      )
    );
  }
  // Everything else (API calls, photos, map tiles) goes straight to the network.
});
"""


class PWARenderer:
	"""Custom page renderer registered in hooks.page_renderer."""

	def __init__(self, path=None, http_status_code=None):
		self.path = (path or "").strip("/ ")
		self.http_status_code = http_status_code or 200

	def can_render(self):
		return self.path in (MANIFEST_PATH, SW_PATH)

	def render(self):
		if self.path == MANIFEST_PATH:
			body, mimetype = json.dumps(manifest(), indent=1), "application/manifest+json"
		else:
			body, mimetype = SERVICE_WORKER.replace("__VERSION__", str(get_build_version())), "text/javascript"

		response = Response(body, status=self.http_status_code, mimetype=mimetype)
		response.headers["Cache-Control"] = "no-cache"
		return response
